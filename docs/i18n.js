const I18N = {
  lang: "en",
  init() {
    let saved = null;
    try { saved = localStorage.getItem("hsj-lang"); } catch (e) { /* storage blocked */ }
    const fromUrl = new URLSearchParams(location.search).get("lang");
    const browser = (navigator.language || "en").slice(0, 2).toLowerCase();
    this.lang = [fromUrl, saved, browser].find((l) => l === "en" || l === "de") || "en";
    this.apply();
  },
  set(lang) {
    this.lang = lang;
    try { localStorage.setItem("hsj-lang", lang); } catch (e) { /* storage blocked */ }
    this.apply();
  },
  // t("key", {n: 3}) -> text with {n} replaced; falls back to English, then to the key's last part
  t(key, vars) {
    let s = STRINGS[this.lang][key] ?? STRINGS.en[key] ?? key.replace(/^[a-z]+\./, "");
    if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, v);
    return s;
  },
  locale() { return this.lang === "de" ? "de-DE" : "en-GB"; },
  apply(root = document) {
    document.documentElement.lang = this.lang;
    root.querySelectorAll("[data-i18n]").forEach((e) => { e.textContent = this.t(e.dataset.i18n); });
    root.querySelectorAll("[data-i18n-html]").forEach((e) => { e.innerHTML = this.t(e.dataset.i18nHtml); });
    root.querySelectorAll("[data-i18n-attr]").forEach((e) => {
      e.dataset.i18nAttr.split(";").forEach((pair) => {
        const [attr, key] = pair.split(":");
        e.setAttribute(attr.trim(), this.t(key.trim()));
      });
    });
    const title = document.querySelector("title[data-i18n-key]");
    if (title) document.title = this.t(title.dataset.i18nKey);
    const desc = document.querySelector('meta[name="description"]');
    if (desc && desc.dataset.i18nKey) desc.content = this.t(desc.dataset.i18nKey);
  },
};
const t = (k, v) => I18N.t(k, v);
